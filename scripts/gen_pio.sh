#!/usr/bin/env bash
# Regenerate the PIO opcode headers from the .pio sources using pioasm:
#   drivers/dp_pio/probe_pio.h, drivers/dp_pio/autobaud_pio.h and
#   drivers/sbw_pio/sbw_pio_program.h
#
# The PIO opcodes MUST come out of pioasm (the proven assembler), never by hand.
# This is the parity guarantee for timing-critical code we cannot test on
# hardware: re-running this script must reproduce probe_pio.h byte-for-byte.
#
# pioasm's "-o c-sdk" output is post-processed (awk, below) into the Zephyr
# RPI_PICO_PIO_DEFINE_PROGRAM form: we keep the pioasm-emitted opcodes,
# _wrap_target/_wrap, and the public label _offset_* defines, and drop the
# pico-sdk-only bits (the "hardware/pio.h" include, the raw `pio_program`
# struct, and the `*_get_default_config` init helper) because the Zephyr
# driver builds the pio_program (via the macro) and does SM config itself.
set -euo pipefail

APP_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PIOASM_SRC="$HOME/Developer/zephyrproject/modules/hal/rpi_pico/tools/pioasm"
BUILD="$APP_DIR/build/pioasm"

# Pin the version string so the output is deterministic. It only appears in a
# comment that we strip anyway, but pioasm refuses to build without it. Value
# tracks modules/hal/rpi_pico/pico_sdk_version.cmake (PICO_SDK_VERSION_STRING).
PIOASM_VERSION_STRING="2.2.0"

cmake -S "$PIOASM_SRC" -B "$BUILD" -DCMAKE_BUILD_TYPE=Release \
      -DPIOASM_VERSION_STRING="$PIOASM_VERSION_STRING" >/dev/null
cmake --build "$BUILD" --parallel >/dev/null
PIOASM="$BUILD/pioasm"

OUT="$APP_DIR/drivers/dp_pio/probe_pio.h"
OUT_AUTOBAUD="$APP_DIR/drivers/dp_pio/autobaud_pio.h"
OUT_SBW="$APP_DIR/drivers/sbw_pio/sbw_pio_program.h"

# awk transform of one pioasm c-sdk program block into:
#   #define <name>_offset_* ...      (kept verbatim)
#   RPI_PICO_PIO_DEFINE_PROGRAM(<name>, <wrap_target>, <wrap>,
#       0x...., /* NN: disasm */
#       ...,
#       0xLAST);
# We never alter an opcode; we only re-shape pioasm's emitted values. Opcode
# lines are buffered and flushed at the closing "};" so the last entry can be
# emitted without a trailing comma and with the macro's ");" terminator.
emit_program() {
    "$PIOASM" -o c-sdk "$1" | awk '
        function flush_array(   i) {
            for (i = 1; i <= n; i++) {
                if (i < n) {
                    print "\t" op[i] ","
                } else {
                    print "\t" op[i] ");"
                }
            }
            n = 0
        }
        # --- program metadata ---
        /^#define [a-z_]+_wrap_target / { name=$2; sub(/_wrap_target$/, "", name); wt=$3; next }
        /^#define [a-z_]+_wrap /         { wrap=$3; next }
        /^#define [a-z_]+_pio_version /  { next }              # pico-sdk only
        # --- public label offsets: keep verbatim ---
        /^#define [a-z_]+_offset_/ { print; next }
        # --- start of opcode array: open the macro ---
        /^static const uint16_t .*_program_instructions\[\] = \{/ {
            print "RPI_PICO_PIO_DEFINE_PROGRAM(" name ", " wt ", " wrap ",";
            inarr=1; n=0; next
        }
        inarr {
            if ($0 ~ /^\};/) { flush_array(); inarr=0; next }  # end of array
            if ($0 ~ /\.wrap/) { next }                        # drop // .wrap markers
            # opcode line: "    0xXXXX, // NN: disasm" -> "0xXXXX /* NN: disasm */"
            entry=$0
            opcode=entry; sub(/^[[:space:]]*/, "", opcode); sub(/,.*$/, "", opcode)
            comment=entry; sub(/^[^\/]*\/\/[[:space:]]*/, "", comment)
            sub(/[[:space:]]+$/, "", comment)
            op[++n] = opcode " /* " comment " */"
            next
        }
        # everything else (version banner, #pragma once, #if !PICO_NO_HARDWARE
        # include block, the raw pio_program struct, *_get_default_config) dropped
        { next }
    '
}

{
    echo "/*"
    echo " * GENERATED by scripts/gen_pio.sh from probe.pio / probe_oen.pio. Do not edit."
    echo " *"
    echo " * The opcodes below are produced by pioasm from the .pio sources and reshaped"
    echo " * into Zephyr's RPI_PICO_PIO_DEFINE_PROGRAM form. To change the PIO program,"
    echo " * edit the .pio source and re-run scripts/gen_pio.sh -- never hand-edit opcodes."
    echo " */"
    echo "#pragma once"
    echo "#include <zephyr/drivers/misc/pio_rpi_pico/pio_rpi_pico.h>"
    echo
    emit_program "$APP_DIR/drivers/dp_pio/probe.pio"
    echo
    emit_program "$APP_DIR/drivers/dp_pio/probe_oen.pio"
} > "$OUT"

echo "wrote $OUT"

{
    echo "/*"
    echo " * GENERATED by scripts/gen_pio.sh from autobaud.pio. Do not edit."
    echo " *"
    echo " * The opcodes below are produced by pioasm from the .pio source and reshaped"
    echo " * into Zephyr's RPI_PICO_PIO_DEFINE_PROGRAM form. To change the PIO program,"
    echo " * edit the .pio source and re-run scripts/gen_pio.sh -- never hand-edit opcodes."
    echo " */"
    echo "#pragma once"
    echo "#include <zephyr/drivers/misc/pio_rpi_pico/pio_rpi_pico.h>"
    echo
    emit_program "$APP_DIR/drivers/dp_pio/autobaud.pio"
} > "$OUT_AUTOBAUD"

echo "wrote $OUT_AUTOBAUD"

{
    echo "/*"
    echo " * GENERATED by scripts/gen_pio.sh from sbw.pio. Do not edit."
    echo " *"
    echo " * The opcodes below are produced by pioasm from the .pio source and reshaped"
    echo " * into Zephyr's RPI_PICO_PIO_DEFINE_PROGRAM form. To change the PIO program,"
    echo " * edit the .pio source and re-run scripts/gen_pio.sh -- never hand-edit opcodes."
    echo " */"
    echo "#pragma once"
    echo "#include <zephyr/drivers/misc/pio_rpi_pico/pio_rpi_pico.h>"
    echo
    emit_program "$APP_DIR/drivers/sbw_pio/sbw.pio"
} > "$OUT_SBW"

echo "wrote $OUT_SBW"
